CREATE TABLE network_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    device_type VARCHAR(30) NOT NULL,
    manufacturer VARCHAR(80),
    model VARCHAR(80),
    ip_address VARCHAR(45) NOT NULL,
    location VARCHAR(120),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    notes VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_network_devices_ip_address UNIQUE (ip_address)
);

CREATE INDEX idx_network_devices_device_type ON network_devices (device_type);
CREATE INDEX idx_network_devices_status ON network_devices (status);
CREATE INDEX idx_network_devices_name ON network_devices (name);
